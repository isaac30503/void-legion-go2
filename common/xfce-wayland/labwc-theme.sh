#!/bin/sh
# labwc-theme.sh — Orchis-Teal-Dark-Compact for labwc's window borders ("Xfce (Wayland)"),
# taken from the xfwm4 theme that is already in ~/.themes (docs/5-desktop/2-look-and-feel.md): same colors, bar height,
# border and buttons (Orchis's SVGs, renamed as labwc looks for them). Orchis does not ship a labwc theme.
# It leaves ~/.local/share/themes/Orchis-Teal-Dark-Compact/labwc/ (it does not touch ~/.themes, which is restored
# entirely from orchis-themes.tar.gz). labwc's rc.xml names it in <theme><name>. Without sudo.
#   sh common/xfce-wayland/labwc-theme.sh          (re)makes it and reloads labwc if it is running
# docs/5-desktop/2-look-and-feel.md. Previous (Spanish) name: tema-labwc.sh.
set -e
R=$(dirname "$(readlink -f "$0")"); until [ -f "$R/lib/common.sh" ] || [ "$R" = / ]; do R=$(dirname "$R"); done
. "$R/lib/common.sh"
O="$HOME/.themes/Orchis-Teal-Dark-Compact/xfwm4"
L="$HOME/.local/share/themes/Orchis-Teal-Dark-Compact/labwc"
[ -d "$O" ] || { t "!! %s is missing (docs/5-desktop/2-look-and-feel.md)" "$O"; exit 1; }
mkdir -p "$L"

# Buttons: xfwm4 → labwc. prelight = mouse over (_hover), maximize-toggled = maximized window.
for e in active inactive; do
    cp "$O/close-$e.svg"             "$L/close-$e.svg"
    cp "$O/hide-$e.svg"              "$L/iconify-$e.svg"
    cp "$O/maximize-$e.svg"          "$L/max-$e.svg"
    cp "$O/maximize-toggled-$e.svg"  "$L/max_toggled-$e.svg"
    cp "$O/shade-$e.svg"             "$L/shade-$e.svg"
    cp "$O/menu-$e.svg"              "$L/menu-$e.svg"
    cp "$O/close-prelight.svg"            "$L/close_hover-$e.svg"
    cp "$O/hide-prelight.svg"             "$L/iconify_hover-$e.svg"
    cp "$O/maximize-prelight.svg"         "$L/max_hover-$e.svg"
    cp "$O/maximize-toggled-prelight.svg" "$L/max_toggled_hover-$e.svg"
    cp "$O/shade-prelight.svg"            "$L/shade_hover-$e.svg"
    cp "$O/menu-prelight.svg"             "$L/menu_hover-$e.svg"
done

# Colors and sizes: those of xfwm4's .xpm (title-1-*, left-*, bottom-*) and of gtk-3.0 (text).
cat > "$L/themerc" <<'EOF'
# Orchis-Teal-Dark-Compact for labwc (generated by labwc-theme.sh from the xfwm4 theme).
border.width: 2
padding.height: 0
window.titlebar.padding.width: 3
window.titlebar.padding.height: 0
# Border of the focused window in teal, like Alt+Tab's outline (the user's request,
# 2026-10-03); the others, gray like their bar.
window.active.border.color: #4db6ac
window.inactive.border.color: #333333
window.active.indicator.toggled-keybind.color: #2c2c2c
window.active.title.bg: Solid
window.active.title.bg.color: #2c2c2c
window.inactive.title.bg: Solid
window.inactive.title.bg.color: #333333
window.active.label.text.color: #ffffff
window.inactive.label.text.color: #ffffff80
window.label.text.justify: center
window.button.width: 34
window.button.height: 34
window.button.spacing: 0
window.button.hover.bg.color: #00000000
window.active.button.unpressed.image.color: #ffffff
window.inactive.button.unpressed.image.color: #ffffff80
window.active.shadow.size: 20
window.inactive.shadow.size: 12
window.active.shadow.color: #00000066
window.inactive.shadow.color: #00000040
menu.border.width: 1
menu.border.color: #3c3c3c
menu.items.bg.color: #2c2c2c
menu.items.text.color: #ffffff
menu.items.active.bg.color: #4db6ac
menu.items.active.text.color: #ffffff
menu.separator.color: #3c3c3c
menu.title.bg.color: #2c2c2c
menu.title.text.color: #ffffff
# On-screen notices and Alt+Tab: like Orchis's bottom panel (.xfce4-panel.background in
# gtk-3.0/gtk.css: background rgba(33,33,33,.65), text rgba(255,255,255,.7); button highlight = white
# veil, without border). The corners cannot be rounded: labwc 0.20 has no option for that.
osd.bg.color: #212121a6
osd.border.color: #21212100
osd.border.width: 0
osd.label.text.color: #ffffffb3
osd.window-switcher.style-classic.item.active.border.color: #4db6ac
osd.window-switcher.style-thumbnail.width.max: 90%
osd.window-switcher.style-thumbnail.padding: 8
osd.window-switcher.style-thumbnail.item.width: 200
osd.window-switcher.style-thumbnail.item.height: 150
osd.window-switcher.style-thumbnail.item.padding: 8
osd.window-switcher.style-thumbnail.item.active.border.width: 0
osd.window-switcher.style-thumbnail.item.active.border.color: #ffffff00
osd.window-switcher.style-thumbnail.item.active.bg.color: #ffffff1f
osd.window-switcher.style-thumbnail.item.icon.size: 32
osd.window-switcher.preview.border.width: 2
osd.window-switcher.preview.border.color: #4db6ac
osd.workspace-switcher.boxes.width: 20
osd.workspace-switcher.boxes.height: 14
EOF
ls "$L" | wc -l
if [ -n "$LABWC_PID" ] && kill -0 "$LABWC_PID" 2>/dev/null; then labwc --reconfigure; t "== labwc reloaded"; fi
t "== theme in %s" "$L"
